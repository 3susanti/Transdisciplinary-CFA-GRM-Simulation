# SECTION 6: MONTE CARLO REPLICATION STUDY (PARAMETER RECOVERY)
# =============================================================================
# Sections 1-5 analyse ONE simulated dataset. This section repeats
# generate -> CFA -> GRM MC_REPS times for each sample size in MC_N. The TRUE
# population parameters stay fixed (Phi, a_params, b_params from Section 1);
# only the latent traits and the item responses are redrawn.
#
# Reported per parameter: bias, relative bias, RMSE, empirical SD, mean SE,
# SE bias, and 95% CI coverage. Reported per sample size: convergence and
# admissibility rates, the Type I error rate of the scaled chi-square test,
# mean robust fit indices, and the spread of the TIF peak location.
# Criteria (Muthen & Muthen, 2002): |relative bias| <= 0.10,
# |SE bias| <= 0.10, and coverage between 0.91 and 0.98. Relative bias is not
# computed when |true value| < 0.2 (e.g., b2 ~ 0), where it is unstable.
#
# Scored parameters (all have an exact population value):
#   Phi      : 3 latent correlations (CFA, WLSMV, standardized solution)
#   a, b1-b3 : 36 x 4 GRM item parameters (per-domain unidimensional GRMs)
# CFA loadings are not scored: the data come from a logistic GRM, so the
# probit-metric loadings have no exact population value.
#
# Reproducibility: replication r of condition k uses
# set.seed(MC_SEED + 100000 * k + r), so results do not depend on the number
# of cores. Responses are drawn with a vectorized inverse-CDF step; the
# response model is identical to Section 1, only the random draws differ.
# =============================================================================

