set.seed(SEED)
cat("\n=== [1/9] GENERATING N=1000 SYNTHETIC DATASET ===\n")

N <- 1000L; n_items <- 36L; n_cats <- 4L
items_per_factor <- 12L; n_factors <- 3L

idx_cog <- 1:items_per_factor
idx_aff <- (items_per_factor + 1):(2 * items_per_factor)
idx_con <- (2 * items_per_factor + 1):(3 * items_per_factor)
domain_idx   <- list(Cognitive = idx_cog, Affective = idx_aff, Conative = idx_con)
domain_names <- names(domain_idx)

# Latent correlation matrix (Cognitive-Affective-Conative trade-offs)
Phi <- matrix(0.35, n_factors, n_factors); diag(Phi) <- 1
Phi[1, 2] <- Phi[2, 1] <- 0.40
Phi[1, 3] <- Phi[3, 1] <- 0.35
Phi[2, 3] <- Phi[3, 2] <- 0.48

Theta <- MASS::mvrnorm(N, mu = rep(0, n_factors), Sigma = Phi)

# Item parameters: discrimination (a) and thresholds (b)
a_cog <- seq(1.3, 1.8, length.out = items_per_factor)
a_aff <- seq(0.9, 1.5, length.out = items_per_factor)
a_con <- seq(1.1, 1.7, length.out = items_per_factor)
a_params <- c(a_cog, a_aff, a_con)

b_base  <- matrix(rep(c(-1.2, 0.0, 1.1), n_items), nrow = n_items, byrow = TRUE)
b_noise <- matrix(rnorm(n_items * 3, mean = 0, sd = 0.10), n_items, 3)
b_params <- t(apply(b_base + b_noise, 1, sort))

data_sim <- matrix(NA_integer_, N, n_items)
for (i in 1:n_items) {
  a <- a_params[i]; b <- b_params[i, ]
  f_idx   <- ((i - 1) %/% items_per_factor) + 1
  theta_i <- Theta[, f_idx]
  p_ge2 <- 1 / (1 + exp(-a * (theta_i - b[1])))
  p_ge3 <- 1 / (1 + exp(-a * (theta_i - b[2])))
  p_ge4 <- 1 / (1 + exp(-a * (theta_i - b[3])))
  p1 <- 1 - p_ge2; p2 <- p_ge2 - p_ge3; p3 <- p_ge3 - p_ge4; p4 <- p_ge4
  probs <- cbind(p1, p2, p3, p4)
  probs[probs < 0 | is.na(probs)] <- 0
  probs <- probs / rowSums(probs)
  data_sim[, i] <- apply(probs, 1, function(p) sample(1:4, 1, prob = p))
}
data_sim <- as.data.frame(data_sim)
colnames(data_sim) <- paste0("It", 1:n_items)
for (j in 1:n_items) data_sim[[j]] <- factor(data_sim[[j]], levels = 1:4, ordered = TRUE)
cat("  [OK] Data generation complete.\n")


