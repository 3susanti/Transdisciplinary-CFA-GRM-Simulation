# =============================================================================
# classify_typology(): each label is assigned by explicit which.max/which.min
# comparison. "Balanced-Tripartite" requires the full range across all three
# scores to be below tol. "Conative-Deficit" requires Conative = argmin.
# Profiles not covered by the four theoretical typologies are labeled
# "Undifferentiated" rather than forced into an incorrect category.
# =============================================================================
