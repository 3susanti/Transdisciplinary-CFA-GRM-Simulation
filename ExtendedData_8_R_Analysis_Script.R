# --- Helper: write CSV with UTF-8 BOM (Excel-safe) ---------------------------
write_csv_utf8_bom <- function(data, filename) {
  con <- file(filename, "wb")
  writeBin(charToRaw("\xEF\xBB\xBF"), con)
  write.csv(data, con, row.names = FALSE)
  close(con)
  cat(sprintf("  [OK] %s saved (UTF-8 with BOM)\n", filename))
}

# --- Helper: numeric formatting (3 decimals; bounded p-values) --------------
fmt3  <- function(x) sprintf("%.3f", x)
fmt_p <- function(p) {
  if (is.na(p)) return(NA_character_)
  if (p > 0.999) return("> 0.999")
  if (p < 0.001) return("< 0.001")
  sprintf("%.3f", p)
}

# --- Helper: save figure as TIFF ---------------------------------------------
save_figure <- function(plot, filename, width, height, dpi = 600) {
  out <- paste0(tools::file_path_sans_ext(filename), ".tiff")
  tryCatch({
    ggsave(out, plot = plot, width = width, height = height,
           units = "cm", dpi = dpi, bg = "white",
           limitsize = FALSE, device = "tiff", compression = FIG_COMPRESSION)
    cat(sprintf("  [OK] %s saved (%.1f x %.1f cm, %d dpi, %s)\n",
                out, width, height, dpi, FIG_COMPRESSION))
    .fig_manifest[nrow(.fig_manifest) + 1, ] <<- list(
      File = out, Width_mm = width * 10, Height_mm = height * 10, DPI = dpi
    )
  }, error = function(e) {
    cat(sprintf("  [ERROR] Failed to save %s: %s\n", out, e$message))
  })
}


