fit_grm_domain <- function(item_idx, label) {
  cat(sprintf("  Fitting GRM: %s domain (%d items)...\n", label, length(item_idx)))
  mirt::mirt(data_num[, item_idx], model = 1, itemtype = "graded", verbose = FALSE)
}
