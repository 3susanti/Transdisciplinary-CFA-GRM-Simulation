profiles <- data.frame(
  Respondent = 1:N,
  Cognitive  = theta_cfa[, "Cognitive"],
  Affective  = theta_cfa[, "Affective"],
  Conative   = theta_cfa[, "Conative"]
)

classify_typology <- function(cog, aff, con, tol = 0.3) {
  scores <- c(Cognitive = cog, Affective = aff, Conative = con)
  rng <- max(scores) - min(scores)
  if (rng < tol) return("Balanced-Tripartite")
  dominant  <- names(which.max(scores))
  deficient <- names(which.min(scores))
  if (dominant  == "Cognitive") return("Cognitive-Dominant")
  if (deficient == "Affective") return("Affective-Friction")
  if (deficient == "Conative")  return("Conative-Deficit")
  "Undifferentiated"
}

profiles$Typology <- mapply(classify_typology,
                            profiles$Cognitive,
                            profiles$Affective,
                            profiles$Conative)

n_undiff <- sum(profiles$Typology == "Undifferentiated")
cat(sprintf("  [INFO] %d/%d (%.1f%%) profiles labeled 'Undifferentiated'\n",
            n_undiff, N, 100 * n_undiff / N))

typology_table <- as.data.frame(table(profiles$Typology))
colnames(typology_table) <- c("Typology", "Count")
typology_table$Percentage <- round(typology_table$Count / sum(typology_table$Count) * 100, 1)

get_pct <- function(typo_name) {
  val <- typology_table$Percentage[typology_table$Typology == typo_name]
  if (length(val) == 0) 0 else val
}

