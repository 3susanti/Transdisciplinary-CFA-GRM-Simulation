# Reliability per domain. Both coefficients are computed on the
# POLYCHORIC correlation matrix, so the alpha reported here is ORDINAL alpha
# (Zumbo et al., 2007), not Cronbach's alpha on raw item scores.
compute_domain_reliability <- function(item_idx, label) {
  poly   <- psych::polychoric(data_num[, item_idx])$rho
  a_val  <- tryCatch(psych::alpha(poly)$total$raw_alpha, error = function(e) NA_real_)
  om_val <- tryCatch(psych::omega(poly, nfactors = 1, plot = FALSE)$omega.tot,
                     error = function(e) NA_real_)
  cat(sprintf("  Reliability %s: ordinal alpha = %.3f | omega = %.3f\n", label, a_val, om_val))
  list(poly = poly, alpha = a_val, omega = om_val)
}
rel_by_domain   <- lapply(domain_names, function(nm) compute_domain_reliability(domain_idx[[nm]], nm))
names(rel_by_domain) <- domain_names
alpha_by_domain <- sapply(rel_by_domain, function(x) x$alpha)
omega_by_domain <- sapply(rel_by_domain, function(x) x$omega)

alpha_res <- mean(alpha_by_domain, na.rm = TRUE)
omega_res <- mean(omega_by_domain, na.rm = TRUE)
cat(sprintf("  [OK] Mean ordinal Alpha (3 domains): %.3f\n", alpha_res))
cat(sprintf("  [OK] Mean Omega (3 domains): %.3f\n", omega_res))


