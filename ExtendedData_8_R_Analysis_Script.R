cat("\n=== [2/9] ESTIMATING CFA MODEL (WLSMV) ===\n")

model_3F <- '
Cognitive =~ It1  + It2  + It3  + It4  + It5  + It6  + It7  + It8  + It9  + It10 + It11 + It12
Affective =~ It13 + It14 + It15 + It16 + It17 + It18 + It19 + It20 + It21 + It22 + It23 + It24
Conative  =~ It25 + It26 + It27 + It28 + It29 + It30 + It31 + It32 + It33 + It34 + It35 + It36
'
fit_3F <- lavaan::cfa(model_3F, data = data_sim, estimator = "WLSMV",
                      ordered = names(data_sim))

if (!lavaan::lavInspect(fit_3F, "converged")) {
  stop("[FATAL] CFA model did not converge.")
} else {
  cat("  [OK] CFA model converged.\n")
}
# Heywood check also covers improper standardized loadings
std_lambda <- lavaan::lavInspect(fit_3F, "std")$lambda
if (any(diag(lavaan::lavInspect(fit_3F, "cov.lv")) < 0) ||
    any(abs(std_lambda[std_lambda != 0]) >= 1)) {
  warning("[WARNING] Heywood case detected (negative latent variance or |std. loading| >= 1).")
}
