# --- Data generation (same GRM as Section 1) --------------------------------
mc_generate <- function(n) {
  th  <- MASS::mvrnorm(n, mu = rep(0, n_factors), Sigma = Phi)
  out <- matrix(NA_integer_, n, n_items)
  for (i in seq_len(n_items)) {
    f    <- ((i - 1) %/% items_per_factor) + 1
    p_ge <- plogis(a_params[i] * outer(th[, f], b_params[i, ], "-"))  # P(X >= 2..4)
    u    <- runif(n)
    out[, i] <- 1L + as.integer(rowSums(u < p_ge))
  }
  out <- as.data.frame(out)
  names(out) <- paste0("It", seq_len(n_items))
  out
}

# --- CFA for one replication (same model and estimator as Section 2) --------
mc_fit_cfa <- function(d) {
  out <- list(converged = FALSE, admissible = FALSE,
              r = rep(NA_real_, 3), r_se = rep(NA_real_, 3),
              fit = c(ChiSq_p = NA_real_, CFI = NA_real_, TLI = NA_real_,
                      RMSEA = NA_real_, SRMR = NA_real_),
              error = "")
  fit <- tryCatch(
    suppressWarnings(lavaan::cfa(model_3F, data = d, estimator = "WLSMV",
                                 ordered = names(d))),
    error = function(e) e)
  if (inherits(fit, "error")) {
    out$error <- paste("CFA:", conditionMessage(fit))
    return(out)
  }
  out$converged <- isTRUE(lavaan::lavInspect(fit, "converged"))
  if (!out$converged) return(out)
  std_lambda <- lavaan::lavInspect(fit, "std")$lambda
  out$admissible <- !(any(diag(lavaan::lavInspect(fit, "cov.lv")) < 0) ||
                        any(abs(std_lambda[std_lambda != 0]) >= 1))
  ss <- lavaan::standardizedSolution(fit)
  for (j in seq_len(nrow(mc_pairs))) {
    hit <- ss$op == "~~" &
      ((ss$lhs == mc_pairs[j, 1] & ss$rhs == mc_pairs[j, 2]) |
         (ss$lhs == mc_pairs[j, 2] & ss$rhs == mc_pairs[j, 1]))
    if (sum(hit) == 1) {
      out$r[j]    <- ss$est.std[hit]
      out$r_se[j] <- ss$se[hit]
    }
  }
  fm <- lavaan::fitMeasures(fit)
  g  <- function(nm) if (nm %in% names(fm)) unname(as.numeric(fm[[nm]])) else NA_real_
  out$fit <- c(ChiSq_p = g("pvalue.scaled"),
               CFI     = g(paste0("cfi.", fit_sfx)),
               TLI     = g(paste0("tli.", fit_sfx)),
               RMSEA   = g(paste0("rmsea.", fit_sfx)),
               SRMR    = g("srmr"))
  out
}

# --- GRMs for one replication (same per-domain models as Section 3) ---------
mc_fit_grm <- function(d) {
  cols <- c("a", "b1", "b2", "b3")
  out  <- list(converged = FALSE, se_ok = FALSE,
               a = rep(NA_real_, n_items), a_se = rep(NA_real_, n_items),
               b = matrix(NA_real_, n_items, 3), b_se = matrix(NA_real_, n_items, 3),
               peak = setNames(rep(NA_real_, length(domain_names)), domain_names),
               error = "")
  # one row ("par" or "SE") of an item's coef() matrix, NA if unavailable
  get_row <- function(x, row) {
    if (!is.matrix(x) || !all(cols %in% colnames(x))) return(rep(NA_real_, 4))
    if (row %in% rownames(x)) return(as.numeric(x[row, cols]))
    if (row == "par") return(as.numeric(x[1, cols]))
    rep(NA_real_, 4)
  }
  conv  <- logical(length(domain_names))
  se_ok <- logical(length(domain_names))
  for (k in seq_along(domain_names)) {
    idx <- domain_idx[[k]]
    its <- names(d)[idx]
    m <- tryCatch(
      suppressWarnings(mirt::mirt(d[, idx], model = 1, itemtype = "graded",
                                  SE = MC_GRM_SE, verbose = FALSE)),
      error = function(e) e)
    if (inherits(m, "error")) {
      out$error <- paste0("GRM ", domain_names[k], ": ", conditionMessage(m))
      return(out)
    }
    conv[k] <- isTRUE(mirt::extract.mirt(m, "converged"))
    est_k <- NULL
    se_k  <- matrix(NA_real_, length(idx), 4)
    if (MC_GRM_SE) {
      # IRT-metric SEs via the delta method (rows "par" and "SE" per item)
      cs <- tryCatch(coef(m, IRTpars = TRUE, printSE = TRUE), error = function(e) NULL)
      est_k <- t(vapply(its, function(it) get_row(cs[[it]], "par"), numeric(4)))
      se_k  <- t(vapply(its, function(it) get_row(cs[[it]], "SE"),  numeric(4)))
      se_ok[k] <- isTRUE(mirt::extract.mirt(m, "secondordertest")) && all(is.finite(se_k))
    }
    if (is.null(est_k) || !all(is.finite(est_k))) {
      # same extraction as Section 3
      p     <- coef(m, IRTpars = TRUE, simplify = TRUE)$items
      est_k <- p[, cols, drop = FALSE]
    }
    out$a[idx]     <- est_k[, 1]
    out$b[idx, ]   <- est_k[, 2:4]
    out$a_se[idx]  <- se_k[, 1]
    out$b_se[idx, ] <- se_k[, 2:4]
    tif <- mirt::testinfo(m, theta_range)
    out$peak[k] <- theta_range[which.max(tif)]
  }
  out$converged <- all(conv)
  out$se_ok     <- all(se_ok)
  out
}

# --- One replication ---------------------------------------------------------
mc_one_rep <- function(r, n, cond) {
  seed_r <- MC_SEED + 100000L * as.integer(cond) + as.integer(r)
  set.seed(seed_r)
  t0 <- proc.time()[["elapsed"]]
  d  <- mc_generate(n)
  cats_ok <- all(vapply(d, function(x) length(unique(x)) == n_cats, logical(1)))
  est <- rep(NA_real_, n_par)
  se  <- rep(NA_real_, n_par)
  cfa <- NULL
  grm <- NULL
  if (cats_ok) {
    cfa <- mc_fit_cfa(d)
    grm <- mc_fit_grm(d)
    est <- c(cfa$r,    grm$a,    as.vector(grm$b))
    se  <- c(cfa$r_se, grm$a_se, as.vector(grm$b_se))
  }
  pick <- function(x, nm) if (is.null(x)) NA_real_ else unname(x[[nm]])
  errs <- c(if (!cats_ok) "empty response category", cfa$error, grm$error)
  info <- data.frame(
    N = n, Rep = r, Seed = seed_r, Cats_OK = cats_ok,
    CFA_Converged  = cats_ok && cfa$converged,
    CFA_Admissible = cats_ok && cfa$admissible,
    GRM_Converged  = cats_ok && grm$converged,
    GRM_SE_OK      = cats_ok && grm$se_ok,
    ChiSq_p = pick(cfa$fit, "ChiSq_p"),
    CFI     = pick(cfa$fit, "CFI"),
    TLI     = pick(cfa$fit, "TLI"),
    RMSEA   = pick(cfa$fit, "RMSEA"),
    SRMR    = pick(cfa$fit, "SRMR"),
    Peak_Cognitive = pick(grm$peak, "Cognitive"),
    Peak_Affective = pick(grm$peak, "Affective"),
    Peak_Conative  = pick(grm$peak, "Conative"),
    Seconds = proc.time()[["elapsed"]] - t0,
    Error   = paste(errs[nzchar(errs)], collapse = "; "),
    stringsAsFactors = FALSE
  )
  list(info = info, est = est, se = se)
}

# --- One sample-size condition, chunked with checkpoint/resume ---------------
mc_run_condition <- function(n, cond, cl = NULL) {
  ckpt <- sprintf("MC_raw_results_N%d.rds", n)
  st   <- list(reps = MC_REPS, n = n, cond = cond, seed = MC_SEED,
               grm_se = MC_GRM_SE, a = a_params, b = b_params, phi = Phi)
  res  <- vector("list", MC_REPS)
  if (MC_RESUME && file.exists(ckpt)) {
    old <- tryCatch(readRDS(ckpt), error = function(e) NULL)
    if (!is.null(old) && identical(old$settings, st)) {
      res <- old$results
      cat(sprintf("  [RESUME] N = %d: %d/%d replications loaded from %s\n",
                  n, sum(!vapply(res, is.null, logical(1))), MC_REPS, ckpt))
    } else {
      cat(sprintf("  [INFO] %s was made with other settings; N = %d restarts.\n", ckpt, n))
    }
  }
  todo <- which(vapply(res, is.null, logical(1)))
  t_start <- proc.time()[["elapsed"]]
  n_done_now <- 0L
  while (length(todo) > 0) {
    idx <- head(todo, MC_CHUNK)
    out <- if (is.null(cl)) {
      lapply(idx, mc_one_rep, n = n, cond = cond)
    } else {
      parallel::parLapplyLB(cl, idx, mc_one_rep, n = n, cond = cond)
    }
    res[idx] <- out
    saveRDS(list(settings = st, results = res), ckpt)
    todo <- setdiff(todo, idx)
    n_done_now <- n_done_now + length(idx)
    el <- proc.time()[["elapsed"]] - t_start
    cat(sprintf("  N = %4d | %3d/%d done | %5.1f min elapsed | ~%5.1f min left\n",
                n, MC_REPS - length(todo), MC_REPS, el / 60,
                el / n_done_now * length(todo) / 60))
  }
  res
}

# --- Summaries ---------------------------------------------------------------
mc_collect <- function(res) {
  list(info = do.call(rbind, lapply(res, `[[`, "info")),
       est  = do.call(rbind, lapply(res, `[[`, "est")),
       se   = do.call(rbind, lapply(res, `[[`, "se")))
}

mc_param_table <- function(cc, n) {
  z <- qnorm(0.975)
  rows <- lapply(seq_len(n_par), function(j) {
    ok <- if (mc_true$Group[j] == "Phi") cc$info$CFA_Admissible else cc$info$GRM_Converged
    e  <- cc$est[ok, j]
    s  <- cc$se[ok, j]
    keep <- is.finite(e)
    e  <- e[keep]
    s  <- s[keep]
    tv <- mc_true$True[j]
    if (length(e) < 2) {
      return(data.frame(Reps_Used = length(e), Mean_Est = NA_real_, Bias = NA_real_,
                        Rel_Bias = NA_real_, Emp_SD = NA_real_, RMSE = NA_real_,
                        Mean_SE = NA_real_, SE_Bias = NA_real_, Coverage_95 = NA_real_))
    }
    emp_sd  <- sd(e)
    s_ok    <- is.finite(s)
    mean_se <- if (any(s_ok)) mean(s[s_ok]) else NA_real_
    data.frame(Reps_Used   = length(e),
               Mean_Est    = mean(e),
               Bias        = mean(e) - tv,
               Rel_Bias    = if (abs(tv) >= 0.2) (mean(e) - tv) / tv else NA_real_,
               Emp_SD      = emp_sd,
               RMSE        = sqrt(mean((e - tv)^2)),
               Mean_SE     = mean_se,
               SE_Bias     = (mean_se - emp_sd) / emp_sd,
               Coverage_95 = if (any(s_ok)) mean(abs(e[s_ok] - tv) <= z * s[s_ok]) else NA_real_)
  })
  cbind(data.frame(N = n, mc_true, stringsAsFactors = FALSE), do.call(rbind, rows))
}

mc_group_table <- function(pt) {
  grp <- split(pt, list(pt$N, pt$Group, pt$Domain), drop = TRUE)
  agg <- do.call(rbind, lapply(grp, function(g) {
    rb <- g$Rel_Bias[is.finite(g$Rel_Bias)]
    data.frame(N = g$N[1], Group = g$Group[1], Domain = g$Domain[1],
               n_Params         = nrow(g),
               Reps_Used        = min(g$Reps_Used),
               Mean_Bias        = mean(g$Bias),
               Max_Abs_Rel_Bias = if (length(rb) > 0) max(abs(rb)) else NA_real_,
               Mean_RMSE        = mean(g$RMSE),
               Max_Abs_SE_Bias  = max(abs(g$SE_Bias)),
               Mean_Coverage    = mean(g$Coverage_95),
               Min_Coverage     = min(g$Coverage_95),
               Max_Coverage     = max(g$Coverage_95),
               stringsAsFactors = FALSE)
  }))
  agg$Criteria_Met <- (is.na(agg$Max_Abs_Rel_Bias) | agg$Max_Abs_Rel_Bias <= 0.10) &
    agg$Max_Abs_SE_Bias <= 0.10 & agg$Min_Coverage >= 0.91 & agg$Max_Coverage <= 0.98
  dom_order <- c(domain_names, unique(mc_true$Domain[mc_true$Group == "Phi"]))
  agg <- agg[order(-agg$N, match(agg$Group, c("Phi", "a", "b1", "b2", "b3")),
                   match(agg$Domain, dom_order)), ]
  rownames(agg) <- NULL
  agg
}

mc_fit_table <- function(info, n) {
  qq <- function(x, p) unname(stats::quantile(x, p, na.rm = TRUE))
  spread <- function(x) sprintf("%.2f [%.2f, %.2f]", mean(x, na.rm = TRUE),
                                qq(x, 0.025), qq(x, 0.975))
  ok  <- info$CFA_Admissible
  okg <- info$GRM_Converged
  data.frame(
    N                    = n,
    Replications         = nrow(info),
    With_Errors          = sum(nzchar(info$Error)),
    All_Categories_Used  = sum(info$Cats_OK),
    CFA_Converged        = sum(info$CFA_Converged),
    CFA_Admissible       = sum(ok),
    GRM_Converged        = sum(okg),
    GRM_SE_OK            = sum(info$GRM_SE_OK),
    Mean_CFI             = mean(info$CFI[ok], na.rm = TRUE),
    Mean_TLI             = mean(info$TLI[ok], na.rm = TRUE),
    Mean_RMSEA           = mean(info$RMSEA[ok], na.rm = TRUE),
    Mean_SRMR            = mean(info$SRMR[ok], na.rm = TRUE),
    ChiSq_Reject_Rate_05 = mean(info$ChiSq_p[ok] < 0.05, na.rm = TRUE),
    Peak_Theta_Cognitive = spread(info$Peak_Cognitive[okg]),
    Peak_Theta_Affective = spread(info$Peak_Affective[okg]),
    Peak_Theta_Conative  = spread(info$Peak_Conative[okg]),
    Mean_Seconds_per_Rep = mean(info$Seconds),
    stringsAsFactors = FALSE
  )
}

round_df <- function(df, digits = 3) {
  num <- vapply(df, is.double, logical(1))
  df[num] <- lapply(df[num], round, digits = digits)
  df
}

