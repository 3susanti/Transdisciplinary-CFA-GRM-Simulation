# With estimator = "WLSMV", fitMeasures(fit, "chisq") is the UNSCALED
# DWLS statistic, and "cfi"/"tli"/"rmsea" are the naive indices built on it.
# The correct test is the scaled (mean- and variance-adjusted) chi-square;
# CFI/TLI/RMSEA are taken from the robust versions, falling back to the
# scaled versions if the installed lavaan does not provide robust indices
# for categorical data. Names are looked up safely across lavaan versions.
fm_all <- lavaan::fitMeasures(fit_3F)
fm_get <- function(name) {
  if (name %in% names(fm_all)) unname(as.numeric(fm_all[[name]])) else NA_real_
}
