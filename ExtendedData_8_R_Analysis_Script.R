MC_N      <- c(1000L, 300L)   # 1,000 = this article; 300 = planned field study - DO NOT CHANGE
MC_SEED   <- SEED             # DO NOT CHANGE
MC_GRM_SE <- TRUE             # GRM standard errors (needed for coverage)
MC_CHUNK  <- 25L              # replications per progress report / checkpoint
MC_RESUME <- TRUE             # reuse MC_raw_results_N*.rds if settings match
MC_CORES  <- local({
  nc <- parallel::detectCores(logical = FALSE)
